"""Writes docs/reference_trips.md: the prototype's step-by-step result for each row of data/test_cases.csv.

Usage, from the project root:
    py -I -X utf8 -B reference/trace_cases.py . docs/reference_trips.md
"""
import sys, csv, importlib.util
root = sys.argv[1]; out = sys.argv[2]
spec = importlib.util.spec_from_file_location("proto", root + "/reference/prototype.py")
P = importlib.util.module_from_spec(spec); spec.loader.exec_module(P)
net = P.Network(root + "/data")
rows = list(csv.DictReader(open(root + "/data/test_cases.csv", encoding="utf-8")))
L = []
w = L.append
w("# Reference trips: step-by-step trace of the 15 test cases\n")
w("Generated by running `reference/prototype.py` (`Network.locate`, `find_route`, `to_steps`, `fare`) on the files in `data/`. "
  "This is the expected behavior for spec 04 (routing) and spec 05 (fares). Do not edit by hand; regenerate it if the prototype or the data change.\n")
w("Conventions: times are real seconds (no penalties). `wait` is the average wait added at boarding. "
  "A ride's `sec` includes its wait. `t0` is the second, counted from departure, when the step starts (used by the 90-minute fare window). "
  "Minutes in `test_cases.csv` are `round(total_sec / 60)`.\n")
ok = 0
for i, r in enumerate(rows, 1):
    o, d = net.locate(r["origin"]), net.locate(r["destination"])
    res = net.find_route(o, d)
    rides = [p for p in res["steps"] if p["kind"] == "ride"]
    veh = " > ".join(p["short"] for p in rides) or "walk"
    mins = round(res["sec"] / 60); tr = max(len(rides) - 1, 0)
    match = (str(mins) == r["minutes"] and str(res["cost"]) == r["cost_cop"] and str(tr) == r["transfers"] and veh == r["vehicles"])
    ok += match
    direct = P.haversine_m(*o, *d)
    w(f"\n## Case {i}: {r['origin']} -> {r['destination']}\n")
    w(f"- Origin located at ({o[0]:.6f}, {o[1]:.6f}); destination at ({d[0]:.6f}, {d[1]:.6f}); straight distance {direct:.0f} m "
      f"(walk-only would take {P.walk_sec(direct):.0f} s).")
    w(f"- Places within 500 m: {len(net.nearby(*o))} of the origin, {len(net.nearby(*d))} of the destination.")
    w(f"- Result: **{res['sec']:.0f} s ({mins} min), {res['cost']} COP, {tr} transfers, `{veh}`**"
      f"{' (walk-only trip)' if res.get('walk_only') else ''}. Matches test_cases.csv: {'yes' if match else 'NO'}.\n")
    w("| # | Step | From / at | To | Meters | Wait s | Stops | Sec | t0 |")
    w("|---|------|-----------|----|--------|--------|-------|-----|----|")
    for j, p in enumerate(res["steps"], 1):
        if p["kind"] == "walk":
            w(f"| {j} | walk | | {p['to']} | {p['m']:.0f} | | | {p['sec']:.0f} | {p.get('t0', 0):.0f} |")
        else:
            w(f"| {j} | ride `{p['short']}` {p['label']} ({p['route_type']}) | {p['from']} | {p['to']} | | {p['wait']:.0f} | {p['stops']} | {p['sec']:.0f} | {p['t0']:.0f} |")
w(f"\nAll {ok} of {len(rows)} cases reproduce `data/test_cases.csv` exactly.\n")
open(out, "w", encoding="utf-8").write("\n".join(L) + "\n")
print("matching cases:", ok, "of", len(rows))
